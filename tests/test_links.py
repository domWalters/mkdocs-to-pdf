PARAMS = [
    pytest.param(href, rel_url, expected, id=f"{scene}: {href!r}")
    for scene, cases in CASES.items()
    for href, rel_url, expected in cases
]


@pytest.mark.parametrize(("href", "rel_url", "expected"), PARAMS)
def test_transform_href(href: str, rel_url: str, expected: str) -> None:
    """Rewrite an href into a single-PDF anchor, leaving external links alone."""
    assert transform_href(href, rel_url) == expected
