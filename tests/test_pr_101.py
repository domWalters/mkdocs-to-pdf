"""
Regression tests for PR #101: HTML tags in section titles and TOC items.

A navigation section title may contain inline HTML (for example a badge
generated by a macro). The plugin should render that HTML instead of showing
it as escaped text.
"""

from types import SimpleNamespace

from bs4 import BeautifulSoup, Tag


def _html(built_pr_101: SimpleNamespace) -> BeautifulSoup:
    """Parse the combined HTML produced for the PR #101 fixture."""
    text = built_pr_101.html_path.read_text(encoding="utf-8")
    return BeautifulSoup(text, "html.parser")


def _section_heading(soup: BeautifulSoup) -> Tag | None:
    """Return the generated heading holding the section title."""
    return next(
        (h for h in soup.find_all("h1") if "Section" in h.get_text()),
        None,
    )


def _section_toc_link(soup: BeautifulSoup) -> Tag | None:
    """Return the table-of-contents link holding the section title."""
    toc = soup.find("article", id="doc-toc")
    assert toc is not None
    return next(
        (a for a in toc.find_all("a") if "Section" in a.get_text()),
        None,
    )


def test_section_title_html_is_not_escaped(built_pr_101: SimpleNamespace) -> None:
    """The `<img>` in a section title renders as an element, not as text."""
    heading = _section_heading(_html(built_pr_101))
    assert heading is not None
    assert heading.find("img") is not None, heading


def test_toc_item_html_is_not_escaped(built_pr_101: SimpleNamespace) -> None:
    """The table of contents keeps the section title's `<img>` element."""
    link = _section_toc_link(_html(built_pr_101))
    assert link is not None
    assert link.find("img") is not None, link
